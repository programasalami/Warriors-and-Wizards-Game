    // The account name sits halfway between the two rules (under PROFILE at Sz(46), under the name at Sz(92)). The text control
    // centres its whole line box, which includes the empty descender space below the letters, so the visible capitals come out
    // ~3px lower than the box centre - hence the nudge up.
    private static readonly int NameCenterY = PageTop + (Sz(46) + Sz(92)) / 2 - 3;

    private void BuildProfilePage(Container page) {
        page.RemoveChildren();

        // Left page: who you are.
        page.AddChild(Text("PROFILE", FontGroup.MyriadPro, TitleSize, LeftPageCenterX, PageTop + Sz(16), UiAnchor.Middle));
        page.AddChild(Rule(LeftPageCenterX, PageTop + Sz(46), LeftPageW - Sz(40)));
        if (_accountName.Length > 0) {
            page.AddChild(Text(_accountName, FontGroup.MyriadPro, 42f, LeftPageCenterX, NameCenterY, UiAnchor.Middle, maxWidth: LeftPageW - 10));
        }
        page.AddChild(Rule(LeftPageCenterX, PageTop + Sz(92), LeftPageW - Sz(40)));

        // Gold on top of fame, flush left (the same left edge as the stat rows below), which leaves the right side of this
        // block free for more visual content later; then the account's lifetime numbers run down the rest of the page.
        const int currencyRowGap = 38;
        var currencyLeft = LeftPageX + Sz(14);
        var goldY = PageTop + Sz(114);
        page.AddChild(CurrencyRow("Console/GoldCoin0", _gold.ToString("N0"), currencyLeft, goldY, leftAligned: true));
        page.AddChild(CurrencyRow("Console/CopperCoin0", _fame.ToString("N0"), currencyLeft, goldY + currencyRowGap, leftAligned: true));
        var currencyRuleY = goldY + currencyRowGap + 26;
        page.AddChild(Rule(LeftPageCenterX, currencyRuleY, LeftPageW - Sz(40)));
        BuildAccountStats(page, currencyRuleY + 26);

        // Right page: the character you last played (see LastPlayedCharacter).
        page.AddChild(Text("LAST PLAYED", FontGroup.MyriadPro, TitleSize, RightPageCenterX, PageTop + Sz(16), UiAnchor.Middle));
        page.AddChild(Rule(RightPageCenterX, PageTop + Sz(46), RightPageW - Sz(40)));

        var champion = LastPlayedCharacter();
        if (champion == null) {
            page.AddChild(Text("No characters yet.", FontGroup.MyriadPro, BodySize, RightPageCenterX, PageTop + Sz(120), UiAnchor.Middle));
            page.AddChild(Text("Open the Characters tab", FontGroup.MyriadPro, SmallSize + 2, RightPageCenterX, PageTop + Sz(150), UiAnchor.Middle));
            page.AddChild(Text("to forge your first character.", FontGroup.MyriadPro, SmallSize + 2, RightPageCenterX, PageTop + Sz(172), UiAnchor.Middle));
            return;
        }

        BuildCharacterSummary(page, champion, includeFame: true);
    }

    // The right-hand readout shared by "Last Played" and "Details": portrait, class, level + experience, (fame for the
    // Last Played character only), all eight stats in two columns, and a PLAY button that launches THIS character.
    private void BuildCharacterSummary(Container page, Character character, bool includeFame) {
        var props = ObjectLibrary.TypeToObjectProps[character.ObjectType];
        var cx = RightPageCenterX;

        page.AddChild(Portrait(character, cx, PageTop + 128, 112));
        page.AddChild(Text(props.ObjectId.ToUpperInvariant(), FontGroup.MyriadPro, 30f, cx, PageTop + 208, UiAnchor.Middle));
        page.AddChild(Text($"LEVEL {character.Level}", CharacterFont, 20f, cx, PageTop + 246, UiAnchor.Middle, color: InkSoft, outline: 1));

        if (includeFame) {
            page.AddChild(CurrencyRow("Console/CopperCoin0", character.CurrentFame.ToString("N0"), cx, PageTop + 284));
        }

        (string Label, int Value)[] stats = [
            ("HP", character.MaxHitPoints), ("MP", character.MaxMagicPoints),
            ("ATT", character.Attack), ("DEF", character.Defense),
            ("SPD", character.Speed), ("DEX", character.Dexterity),
            ("VIT", character.Vitality), ("WIS", character.Wisdom)
        ];
        var top = PageTop + (includeFame ? 330 : 304);
        var step = includeFame ? 32 : 34;
        for (var i = 0; i < stats.Length; i++) {
            page.AddChild(StatLine(stats[i].Label, stats[i].Value.ToString(), cx - 160 + (i % 2) * 170, top + (i / 2) * step));
        }

        page.AddChild(BuildScrollButton("PLAY", cx, PageBottom - PlayButtonBottomGap - PlayButtonHeight / 2, PlayButtonWidth, PlayButtonHeight, () => _onPlay(character)));
    }

    private void BuildCharactersPage(Container page) {
        page.RemoveChildren();

        // Left page: the roster grid, plus a "new character" tile that opens the creation popup.
        page.AddChild(Text("CHARACTERS", FontGroup.MyriadPro, TitleSize, LeftPageCenterX, PageTop + Sz(16), UiAnchor.Middle));

        const int cols = 3;
        const int tile = 122;
        const int gap = 10;
        var gridW = cols * tile + (cols - 1) * gap;
        var gridLeft = LeftPageCenterX - gridW / 2;
        var gridTop = PageTop + Sz(40);

        const int maxTiles = 9;
        var shown = Math.Min(_characters.Count, maxTiles - 1);
        for (var i = 0; i < shown; i++) {
            page.AddChild(BuildCharacterTile(_characters[i], i, gridLeft + (i % cols) * (tile + gap), gridTop + (i / cols) * (tile + gap), tile));
        }
        var newIndex = shown;
        page.AddChild(BuildNewCharacterTile(gridLeft + (newIndex % cols) * (tile + gap), gridTop + (newIndex / cols) * (tile + gap), tile));

        // Right page: the selected character.
        var character = CurrentCharacter;
        page.AddChild(Text("DETAILS", FontGroup.MyriadPro, TitleSize, RightPageCenterX, PageTop + Sz(16), UiAnchor.Middle));
        page.AddChild(Rule(RightPageCenterX, PageTop + Sz(46), RightPageW - Sz(40)));

        if (character == null) {
            page.AddChild(Text("No characters yet.", FontGroup.MyriadPro, BodySize, RightPageCenterX, PageTop + Sz(120), UiAnchor.Middle));
            page.AddChild(BuildTextButton("FORGE A CHARACTER", FontGroup.MyriadPro, 26f, RightPageCenterX, PageTop + Sz(170), UiAnchor.Middle, () => _onForge()));
            return;
        }

        // No fame here: fame belongs to the Last Played (alive) character readout.
        BuildCharacterSummary(page, character, includeFame: false);
    }

    // Left page only (icon + one line) - the right page is deliberately left empty for now.
    private void BuildIconMessagePage(Container page, string title, string iconName, string leftLine) {
        page.RemoveChildren();

