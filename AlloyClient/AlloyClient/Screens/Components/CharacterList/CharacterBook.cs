    private static SimpleText Text(string text, FontGroup font, float size, int x, int y, UiAnchor anchor, uint color = Ink, int maxWidth = 0, int outline = 2) {
        var cfg = new TextConfig {
            Text = text,
            FontSize = size,
            FontType = FontType.Bold,
            FontGroup = font,
            Color = color,
            OutlineColor = color,
            OutlineThickness = outline,
            X = x,
            Y = y,
            Anchor = anchor
        };
        if (maxWidth > 0) {
            cfg.MaxWidth = maxWidth;
        }
        return new SimpleText(cfg);
    }

    private static ColorRect Rule(int centerX, int y, int width) =>
        new(new ColorRectConfig { Width = width, Height = 2, Color = InkSoft, Alpha = 0.6f }) { X = centerX - width / 2, Y = y };

    // Centred icon + number, e.g. the gold and fame readouts.
    private static Container CurrencyRow(string iconLookup, string amount, int centerX, int centerY, bool leftAligned = false) {
        const int icon = 26;
        const int gap = 8;
        var row = new Container();
        var text = Text(amount, FontGroup.MyriadPro, BodySize + 4, 0, centerY, UiAnchor.MiddleLeft);
        var total = icon + gap + text.Width;
        var left = leftAligned ? centerX : centerX - total / 2;     // leftAligned: the x given is the row's left edge
        row.AddChild(new ObjectRect(new ObjectRectConfig {
            Texture = TextureHelper.FromUiAtlas(iconLookup, 0, false),
            X = left + icon / 2,
            Y = centerY,
            Width = icon,
            Height = icon,
            Anchor = UiAnchor.Middle,
            OutlineEnabled = false,
            GlowEnabled = false
        }));
        text.X = left + icon + gap;
        row.AddChild(text);
        return row;
    }

    private static Container StatLine(string label, string value, int left, int centerY) {
        var row = new Container();
        row.AddChild(Text(label, CharacterFont, 20f, left, centerY, UiAnchor.MiddleLeft, color: InkSoft, outline: 1));
        row.AddChild(Text(value, CharacterFont, 22f, left + 64, centerY, UiAnchor.MiddleLeft, outline: 1));
        return row;
    }

    // A label on the left and its value pushed to the right edge, e.g. the Profile page's account stats.
    private static Container AccountStatLine(string label, string value, int left, int right, int centerY) {
        var row = new Container();
        row.AddChild(Text(label, CharacterFont, 16f, left, centerY, UiAnchor.MiddleLeft, color: InkSoft, outline: 1));
        row.AddChild(Text(value, CharacterFont, 20f, right, centerY, UiAnchor.MiddleRight, outline: 1));
        return row;
    }

    private static ObjectRect Portrait(Character character, int centerX, int centerY, int size) {
        var textureData = ObjectLibrary.TypeToTextureData[character.ObjectType];
        return new ObjectRect(new ObjectRectConfig {
            Texture = TextureHelper.Create(textureData.AnimatedTextures.FaceDown[0], TextureType.GameAtlas),
            X = centerX,
            Y = centerY,
            Width = size,
            Height = size,
            Anchor = UiAnchor.Middle,
            OutlineEnabled = false,
            GlowEnabled = false
        });
    }

