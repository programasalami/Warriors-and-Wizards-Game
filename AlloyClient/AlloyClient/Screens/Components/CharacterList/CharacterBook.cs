    #region Tabs

    private void BuildTab(int index) {
        var frame = BookFrameData.Tabs[index];

        var tab = new Container { X = Px(frame.X), Y = Py(frame.Y) };
        tab.MouseEnabled = true;

        var sprite = new ObjectRect(new ObjectRectConfig {
            Texture = TextureHelper.FromUiAtlas($"BookGems/Tab{index + 1}/Idle", 0, false),
            Width = Sz(frame.W),
            Height = Sz(frame.H),
            OutlineEnabled = false,
            GlowEnabled = false
        });
        tab.AddChild(sprite);

        // Icon centred on the tab's blue face (measured from the sprite, see BookFrameData.TabFaceCenter*) at its
        // true aspect ratio - the face sits above the tab's dark lip, so the tab's overall centre would be too low.
        var iconSize = BookFrameData.TabIconSizes[index];
        var icon = new ObjectRect(new ObjectRectConfig {
            Texture = TextureHelper.FromUiAtlas($"BookGems/Icon/{TabIcons[index]}", 0, false),
            X = (int) MathF.Round(BookFrameData.TabFaceCenterX * BookScale),
            Y = (int) MathF.Round(BookFrameData.TabFaceCenterY * BookScale),
            Width = iconSize.W * TabIconScale,
            Height = iconSize.H * TabIconScale,
            Anchor = UiAnchor.Middle,
            OutlineEnabled = false,
            GlowEnabled = false
        });
        tab.AddChild(icon);

        var down = false;
        tab.AddEventListener(MouseEvent.MouseOver, () => SetTabLook(index, true));
        tab.AddEventListener(MouseEvent.MouseOut, () => SetTabLook(index, false));
        tab.AddEventListener(MouseEvent.LeftDown, () => down = true);
        tab.AddEventListener(MouseEvent.LeftUp, () => {
            if (down) {
                GoToPage((BookPage) index);
            }
            down = false;
        });

        tab.Visible = false;
        _tabs[index] = tab;
        _tabSprites[index] = sprite;
        _tabIcons[index] = icon;
        AddChild(tab);
    }

    // The current page's tab always shows its "pulled out" pennant; hovering another tab previews it.
    private void SetTabLook(int index, bool hovering) {
        var active = index == (int) (_flipping ? _flipTarget : _currentPage) || hovering;
        _tabSprites[index].ChangeTexture(TextureHelper.FromUiAtlas($"BookGems/Tab{index + 1}/{(active ? "Active" : "Idle")}", 0, false));
    }

    private void RefreshTabLooks() {
        for (var i = 0; i < 6; i++) {
            SetTabLook(i, false);
        }
    }

    #endregion

    #region Page navigation and flip

    private void GoToPage(BookPage page) {
        if (!_entranceComplete) {
            return;
        }

        if (_flipping) {
            _pendingPage = page;
            return;
        }

        if (page == _currentPage) {
            return;
        }

        StartFlip(page);
    }

    private void StartFlip(BookPage target) {
        if (target is BookPage.Inbox or BookPage.DailySpin or BookPage.DailyGift) {
            RefreshRewards();       // always show what the server says now
        }

        _flipping = true;
        _flipTarget = target;
        _flipForward = target > _currentPage;
        _flipElapsedMs = 0;
        _flipShownFrame = -1;
        _pages[(int) _currentPage].Visible = false;
        _backButton.Visible = false;
        RefreshTabLooks();
    }

    private void UpdateFlip(double dt) {
        _flipElapsedMs += dt;
        var frames = _flipForward ? BookFrameData.FlipLeft : BookFrameData.FlipRight;
        var index = (int) (_flipElapsedMs / FlipFrameMs);

        if (index >= frames.Length) {
            _flip.Visible = false;
            _flipping = false;
            _currentPage = _flipTarget;
            _pages[(int) _currentPage].Alpha = 0f;
            _pages[(int) _currentPage].Visible = true;
            _backButton.Visible = true;
            _pageFadeMs = 0;
            RefreshTabLooks();

            if (_pendingPage.HasValue) {
                var next = _pendingPage.Value;
                _pendingPage = null;
                if (next != _currentPage) {
                    StartFlip(next);
                }
            }
            return;
        }

        if (index != _flipShownFrame) {
            _flipShownFrame = index;
            var f = frames[index];
            _flip.ChangeTexture(TextureHelper.FromUiAtlas($"BookGems/Flip{(_flipForward ? "L" : "R")}/{index + 1}", 0, false));
            _flip.X = Px(f.X);
            _flip.Y = Py(f.Y);
            _flip.Resize(Sz(f.W), Sz(f.H));
            _flip.Visible = true;
        }
    }

    #endregion

    #region Frame loop / entrance

    private void OnFrame() {
        var dt = Stage.GameTime.ElapsedMs;
        UpdateRewards(dt);

        if (!_entranceComplete) {
            UpdateEntrance(dt);
        }

        if (_flipping) {
            UpdateFlip(dt);
        } else if (_entranceComplete && _pageFadeMs < PageFadeMs) {
            _pageFadeMs += dt;
            _pages[(int) _currentPage].Alpha = (float) Math.Clamp(_pageFadeMs / PageFadeMs, 0.0, 1.0);
        }
    }

    private void UpdateEntrance(double dt) {
        _elapsedMs += dt;
        var t = _elapsedMs;

        if (t <= InitialDelayMs) {
            Alpha = 0f;
            return;
        }

        var sinceDelay = t - InitialDelayMs;
        Alpha = sinceDelay < FadeInMs ? IdleAlpha * (float) (sinceDelay / FadeInMs) : IdleAlpha;

        var openStart = InitialDelayMs + FadeInMs + HoldClosedMs;
        if (t < openStart) {
            return;
        }

        var openProgress = (t - openStart) / OpenMs;
        if (openProgress < 1.0) {
            ShowOpening(openProgress);
            return;
        }

        ShowStaticBook();
        var sinceOpen = t - (openStart + OpenMs);

        for (var i = 0; i < 6; i++) {
            var local = sinceOpen - i * TabStaggerMs;
            var p = (float) Math.Clamp(local / TabFadeMs, 0.0, 1.0);
            _tabs[i].Visible = p > 0f;
            _tabs[i].Alpha = p;
            _tabs[i].X = Px(BookFrameData.Tabs[i].X) + (int) ((1f - p) * Sz(12));
        }

        var contentStart = 6 * TabStaggerMs;
        var page = _pages[(int) _currentPage];
        if (sinceOpen >= contentStart) {
            var p = (float) Math.Clamp((sinceOpen - contentStart) / ContentFadeMs, 0.0, 1.0);
            page.Visible = true;
            page.Alpha = p;
            _backButton.Visible = true;
            _backButton.Alpha = p;
        }

        if (sinceOpen >= contentStart + ContentFadeMs) {
            page.Alpha = 1f;
            _backButton.Alpha = 1f;
            _pageFadeMs = PageFadeMs;
            _entranceComplete = true;
            RefreshTabLooks();
        }
    }

    // The book opening, as one continuous motion instead of five hard frame swaps. The art is 5 drawn frames plus the
    // finished static book (index Open.Length); progress 0..1 (eased in and out) sweeps through them, and the frame
    // being left stays underneath while the next one dissolves in over it. Every frame keeps its native position
    // (spine and bottom edge fixed, as the pack drew them), and a single eased slide carries the whole thing from
    // "closed book centred" to "open book centred" - re-centring each frame on its own is what made the spine hop.
    private void ShowOpening(double progress) {
        var eased = 0.5 - 0.5 * Math.Cos(Math.PI * progress);
        var position = eased * BookFrameData.Open.Length;
        var from = Math.Min((int) position, BookFrameData.Open.Length - 1);
        var mix = (float) (position - from);
        var shift = (int) MathF.Round((1f - (float) eased) * ClosedBookOffsetX);

        PlaceBookFrame(_book, ref _shownOpenFrame, from, shift);
        PlaceBookFrame(_bookBlend, ref _shownBlendFrame, from + 1, shift);

        // The next frame dissolves in over the first half; only then does the old one fade out from underneath, so
        // the parts both frames share never go see-through in the middle of the swap.
        _bookBlend.Visible = mix > 0f;
        _bookBlend.Alpha = Math.Min(1f, mix * 2f);
        _book.Alpha = 1f - Math.Max(0f, mix * 2f - 1f);
    }

    // Puts one frame of the opening animation (index Open.Length is the finished book) at its native spot, moved
    // `shift` px sideways.
    private static void PlaceBookFrame(ObjectRect rect, ref int shown, int index, int shift) {
        var isFinal = index >= BookFrameData.Open.Length;
        var f = isFinal ? new BookFrameData.Frame(0, 0, BookFrameData.BookWidth, BookFrameData.BookHeight) : BookFrameData.Open[index];

        if (shown != index) {
            shown = index;
            rect.ChangeTexture(TextureHelper.FromUiAtlas(isFinal ? "BookGems/Book" : $"BookGems/Open/{index + 1}", 0, false));
            rect.Resize(Sz(f.W), Sz(f.H));
        }

        rect.X = Px(f.X) + shift;
        rect.Y = Py(f.Y);
    }

    private void ShowStaticBook() {
        if (_shownOpenFrame == -2) {
            return;
        }
        _shownOpenFrame = -2;
        _bookBlend.Visible = false;
        _book.Alpha = 1f;
        _book.ChangeTexture(TextureHelper.FromUiAtlas("BookGems/Book", 0, false));
        _book.X = Px(0);
        _book.Y = Py(0);
        _book.Resize(Sz(BookFrameData.BookWidth), Sz(BookFrameData.BookHeight));
    }

