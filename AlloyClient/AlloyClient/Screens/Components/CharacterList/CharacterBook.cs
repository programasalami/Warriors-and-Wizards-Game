    // Account-wide numbers for the Profile page: the account's lifetime totals, the best any one character has
    // done (the account server's records, or a live character that has already beaten them), and each class's
    // best level / fame. Rows stop at the bottom of the page, so a longer class roster just gets cut off
    // rather than running off the book.
    private void BuildAccountStats(Container page, int top) {
        var stats = _account?.Stats;
        if (stats == null) {
            return;
        }

        var left = LeftPageX + Sz(14);
        var right = LeftPageX + LeftPageW - Sz(14);
        var rowH = Sz(17);
        var limit = PageBottom - Sz(8);
        var y = top;

        var bestLevel = 0;
        var bestFame = stats.BestCharacterFame;
        foreach (var c in _characters) {
            bestLevel = Math.Max(bestLevel, c.Level);
            bestFame = Math.Max(bestFame, c.CurrentFame);
        }
        foreach (var classStat in stats.ClassStats) {
            bestLevel = Math.Max(bestLevel, classStat.BestLevel);
        }

        var guild = string.IsNullOrEmpty(_account.GuildName) ? "NONE" : _account.GuildName.ToUpperInvariant();
        (string Label, string Value)[] rows = [
            ("CHARACTERS", _characters.Count.ToString("N0")),
            ("HIGHEST LEVEL REACHED", bestLevel.ToString("N0")),
            ("HIGHEST FAME REACHED", bestFame.ToString("N0")),
            ("LIFETIME FAME EARNINGS", (stats.TotalFame + _lifetimeFameEarned).ToString("N0")),
            ("LIFETIME GOLD EARNINGS", (stats.TotalCredits + _lifetimeGoldEarned).ToString("N0")),
            ("GUILD", guild)
        ];
        foreach (var (label, value) in rows) {
            page.AddChild(AccountStatLine(label, value, left, right, y));
            y += rowH;
        }

        if (stats.ClassStats.Length == 0) {
            return;
        }

        // Then a divider and each class's best level / fame.
        y += Sz(6);
        page.AddChild(Rule(LeftPageCenterX, y, LeftPageW - Sz(40)));
        y += Sz(14);

        foreach (var classStat in stats.ClassStats) {
            if (y > limit || !ObjectLibrary.TypeToObjectProps.TryGetValue((ushort) classStat.ObjectType, out var props)) {
                continue;
            }
            page.AddChild(AccountStatLine(props.ObjectId.ToUpperInvariant(), $"LV {classStat.BestLevel}   {classStat.BestFame:N0} FAME", left, right, y));
            y += rowH;
        }
    }

    // The character last launched into the game (Settings.LastPlayedCharacterId, saved on PLAY); if that one is
    // gone or nothing has been played yet, the highest-fame character stands in.
    private Character LastPlayedCharacter() {
        Character best = null;
        foreach (var c in _characters) {
            if (c.Id == (int) Settings.LastPlayedCharacterId) {
                return c;
            }
            if (best == null || c.CurrentFame > best.CurrentFame) {
                best = c;
            }
        }
        return best;
    }

    private Sprite BuildCharacterTile(Character character, int index, int x, int y, int size) {
        var tile = new Container { X = x, Y = y };
        tile.MouseEnabled = true;

        var selected = index == _selectedIndex;
        tile.AddChild(new ColorRect(new ColorRectConfig { Width = size, Height = size, Color = Ink, Alpha = selected ? 0.95f : 0.55f }));
        tile.AddChild(new ColorRect(new ColorRectConfig { Width = size - 4, Height = size - 4, Color = selected ? TileSelected : TileIdle, Alpha = selected ? 0.75f : 0.28f }) { X = 2, Y = 2 });

        var props = ObjectLibrary.TypeToObjectProps[character.ObjectType];
        // Drawn larger than the 32x32 cell suggests because the art only fills about half of its cell; centred in the space above the name.
        tile.AddChild(Portrait(character, size / 2, size / 2 - 19, 88));
        tile.AddChild(Text(props.ObjectId.ToUpperInvariant(), CharacterFont, 16f, size / 2, size - 32, UiAnchor.Middle, maxWidth: size - 8, outline: 1));
        tile.AddChild(Text($"LV {character.Level}", CharacterFont, 14f, size / 2, size - 14, UiAnchor.Middle, color: InkSoft, outline: 1));

        var down = false;
        tile.AddEventListener(MouseEvent.LeftDown, () => down = true);
        tile.AddEventListener(MouseEvent.LeftUp, () => {
            if (down && !_flipping && _entranceComplete) {
                _selectedIndex = index;
                BuildCharactersPage(_pages[(int) BookPage.Characters]);
            }
            down = false;
        });
        return tile;
    }

    private Sprite BuildNewCharacterTile(int x, int y, int size) {
        var tile = new Container { X = x, Y = y };
        tile.MouseEnabled = true;

        tile.AddChild(new ColorRect(new ColorRectConfig { Width = size, Height = size, Color = Ink, Alpha = 0.4f }));
        tile.AddChild(new ColorRect(new ColorRectConfig { Width = size - 4, Height = size - 4, Color = TileIdle, Alpha = 0.10f }) { X = 2, Y = 2 });
        var plus = Text("+", FontGroup.MyriadPro, 48f, size / 2, size / 2 - 12, UiAnchor.Middle, color: InkSoft);
        var label = Text("NEW", CharacterFont, 16f, size / 2, size - 32, UiAnchor.Middle, color: InkSoft, outline: 1);
        tile.AddChild(plus);
        tile.AddChild(label);

        var down = false;
        tile.AddEventListener(MouseEvent.MouseOver, () => { plus.SetColor(Hover); label.SetColor(Hover); });
        tile.AddEventListener(MouseEvent.MouseOut, () => { plus.SetColor(InkSoft); label.SetColor(InkSoft); });
        tile.AddEventListener(MouseEvent.LeftDown, () => down = true);
        tile.AddEventListener(MouseEvent.LeftUp, () => {
            if (down && !_flipping && _entranceComplete) {
                _onForge();
            }
            down = false;
        });
        return tile;
    }

