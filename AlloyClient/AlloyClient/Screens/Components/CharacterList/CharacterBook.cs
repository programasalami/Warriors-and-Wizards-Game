// The character-select "book" (replaces CharacterConsole) - the open book from the "Pocket Inventory
// Series #7 Gems of Status" pack (Desktop/GUI), mostly filling the screen and slightly transparent
// so the forest backdrop shows through. It opens on the Profile page and has six side tabs (icons
// from Desktop/CharacterSelectionPageIcons): Profile, Characters, Graveyard, Inbox, Daily Spin and
// Daily Gift. Only Profile and Characters have real content so far - the other four are "coming
// soon" pages until those features exist. Character creation is NOT a page: the Characters page's
// "new character" tile opens the creation popup (ClassContainer), a wooden frame that sits over the book.
//
// Art layout comes from BookFrameData.g.cs, generated by Tools/BookUi/build_book_assets.py: every
// pack frame shares one canvas, so all positions below are the book's native pixels (relative to
// the static open book's top-left) times BookScale. The page-flip frames are small patches drawn
// over the static book, and the same table covers the open animation and the six tab sprites.
//
// All timing is driven by one EnterFrame accumulator (not Timers) - a Timer created from inside
// another Timer's callback has proven unreliable elsewhere in this UI (see BookOverlay).
public sealed partial class CharacterBook : Container {

    // 672x416 native -> ~1075x666 of the 1280x720 design canvas ("mostly fills the screen"). Not an
    // integer scale, like most sprites in this game.
    private const float BookScale = 1.6f;

    // The opened book is centred on the screen's true centre (x = 640 of the 1280 canvas): its 672px native
    // width * 1.6 = 1075px, so it starts 102px in. The opening frames sit at their own native positions (the spine
    // and the bottom edge stay put, as the art was drawn) plus one smooth sideways slide (see PlaceBookFrame) that
    // starts with the closed book centred on the screen and ends with the open book centred.
    private const int ScreenCenterX = 640;
    private const int BookLeft = ScreenCenterX - 538;
    private const int BookTop = 27;

    // Slightly see-through at rest, per request, so the forest shows through the pages.
    private const float IdleAlpha = 0.93f;

    // Page text areas, native px (inside the pages' own decorative border), and the spine.
    private const int LeftPageNativeLeft = 44;
    private const int LeftPageNativeRight = 298;
    private const int RightPageNativeLeft = 378;
    private const int RightPageNativeRight = 632;
    private const int PageNativeTop = 40;
    private const int PageNativeBottom = 364;

    private static int Px(int nativeX) => BookLeft + (int)MathF.Round(nativeX * BookScale);
    private static int Py(int nativeY) => BookTop + (int)MathF.Round(nativeY * BookScale);
    private static int Sz(int native) => (int)MathF.Round(native * BookScale);

    private static readonly int LeftPageX = Px(LeftPageNativeLeft);
    private static readonly int LeftPageW = Sz(LeftPageNativeRight - LeftPageNativeLeft);
    private static readonly int LeftPageCenterX = LeftPageX + LeftPageW / 2;
    private static readonly int RightPageX = Px(RightPageNativeLeft);
    private static readonly int RightPageW = Sz(RightPageNativeRight - RightPageNativeLeft);
    private static readonly int RightPageCenterX = RightPageX + RightPageW / 2;
    private static readonly int PageTop = Py(PageNativeTop);
    private static readonly int PageBottom = Py(PageNativeBottom);

    // Where the opening animation starts, sideways from the book's native spot (negative = left): the closed book sits
    // on the right half of the pack's canvas, so this pulls its centre back onto the screen's centre. It slides to 0
    // as the book opens.
    private static readonly int ClosedBookOffsetX =
        -(int) MathF.Round((BookFrameData.Open[0].X + BookFrameData.Open[0].W / 2f - BookFrameData.BookWidth / 2f) * BookScale);

    // Entrance: the closed book fades in, holds a short beat, opens frame by frame, then the tabs and the page
    // content settle in one after another. It starts the moment the screen appears - the title -> book hand-off
    // (LoaderFlows.FromTitleToCharacterList) is a short fade with no loader in front of it anymore, so there is no
    // extra waiting built in here.
    private const int InitialDelayMs = 0;
    private const int FadeInMs = 900;
    private const int HoldClosedMs = 250;
    private const int OpenMs = 1000;
    private const int TabStaggerMs = 110;
    private const int TabFadeMs = 300;
    private const int ContentFadeMs = 450;

    // Page flip: 7 patch frames.
    private const int FlipFrameMs = 42;
    private const int PageFadeMs = 160;

    private const uint Ink = 0x2A1C14;
    private const uint InkSoft = 0x6B4A33;
    private const uint Hover = 0x9C4A1A;
    private const uint TileSelected = 0xC79A5B;
    private const uint TileIdle = 0x8A6A4A;

    private const float TitleSize = 32f;
    private const float BodySize = 26f;
    private const float SmallSize = 20f;

    // The Graveyard page has no list behind it yet (nothing records a dead character), so it just says this.
    private const string GraveyardEmpty = "You haven't died yet.";

    // The page icons are 16x16 pixel art, drawn on the tabs at an exact 2x (not the book's 1.6x) so every art pixel stays a clean block.
    private const int TabIconScale = 2;

    // The PLAY button: a parchment scroll (the same piece and look as the character creation popup's buttons) with the label in the
    // book's ink. Both the Last Played and the Details page build it in one place, so it sits at the same spot on each.
    private const int PlayButtonWidth = 190;
    private const int PlayButtonHeight = 50;
    private const int PlayButtonBottomGap = 10;
    private static readonly ColorTransform ScrollHoverTint = new(0.86f, 0.8f, 0.7f, 1f);

    // The BACK button is the sign-in book's back icon (Icons/BookBackIcon, same size and hover as the Register / Sign In forms use).
    private const int BackIconWidth = 40;
    private const int BackIconHeight = 42;
    private const float BackIconHoverScale = 1.15f;

    // Every stat / readout / small label (the cards on the Characters page, the stats on the Last Played / Details pages, the
    // profile stat list) is set in BitPotion, the client's small-text pixel font.
    private const FontGroup CharacterFont = FontGroup.MyriadPro;

    private enum BookPage { Profile, Characters, Graveyard, Inbox, DailySpin, DailyGift }

    private static readonly string[] TabIcons = ["Profile", "Characters", "Graveyard", "Inbox", "DailySpin", "DailyGift"];

    private readonly Action<Character> _onPlay;
    private readonly Action _onForge;
    private readonly Action _onBack;

    private readonly ObjectRect _book;
    private readonly ObjectRect _bookBlend;     // the NEXT opening frame, dissolving in over _book
    private readonly ObjectRect _flip;
    private readonly Container[] _tabs = new Container[6];
    private readonly ObjectRect[] _tabSprites = new ObjectRect[6];
    private readonly ObjectRect[] _tabIcons = new ObjectRect[6];
    private readonly Container[] _pages = new Container[6];
    private readonly Container _backButton;

    private List<Character> _characters = [];
    private int _selectedIndex = -1;
    private int _gold;
    private int _fame;
    private readonly AccountData _account;
    private readonly string _accountName;

    private BookPage _currentPage = BookPage.Profile;
    private BookPage? _pendingPage;

    private double _elapsedMs;
    private bool _entranceComplete;
    private int _shownOpenFrame = -1;
    private int _shownBlendFrame = -1;

    private bool _flipping;
    private bool _flipForward;
    private double _flipElapsedMs;
    private int _flipShownFrame = -1;
